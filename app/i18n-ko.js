// Translate a fragment inside a rule (e.g. "2h ago" in "Uploaded 2h ago").
function tr(text) {
  if (KO[text] !== undefined) return KO[text];
  for (const [re, to] of KO_RULES) if (typeof to === 'string' && re.test(text)) return text.replace(re, to);
  return text;
}

